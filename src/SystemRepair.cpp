#include "SystemRepair.h"
#include "Logger.h"

SystemRepair::SystemRepair(const TargetEnvironment& env) : m_env(env) {}

void SystemRepair::ResetHostsFile() {
    Logger::Log(LogLevel::Info, L"Purging and resetting hosts file...");
    fs::path hostsPath = m_env.targetSystem32Dir / L"drivers" / L"etc" / L"hosts";

    try {
        if (fs::exists(hostsPath)) {
            SetFileAttributesW(hostsPath.c_str(), FILE_ATTRIBUTE_NORMAL);
        }

        std::ofstream hosts(hostsPath, std::ios::trunc);
        if (hosts.is_open()) {
            hosts << "# Copyright (c) 1993-2009 Microsoft Corp.\n";
            hosts << "# Clean baseline hosts generated by Aegis Recovery Tool\n";
            hosts << "127.0.0.1       localhost\n";
            hosts << "::1             localhost\n";
            hosts.close();
            Logger::Log(LogLevel::Success, L"Default hosts file restored successfully.");
        } else {
            Logger::Log(LogLevel::Error, L"Could not open hosts file for writing.");
        }
    } catch (const std::exception& e) {
        Logger::Log(LogLevel::Error, L"Exception in ResetHostsFile: " + ToWide(e.what()));
    }
}

void SystemRepair::ClearSuspiciousTempPaths() {
    Logger::Log(LogLevel::Info, L"Clearing System-wide Temp and Staging directories...");
    std::vector<fs::path> tempDirs = {
        m_env.targetWindowsDir / L"Temp",
        m_env.targetSystem32Dir / L"spool" / L"PRINTERS"
    };

    for (const auto& dir : tempDirs) {
        if (fs::exists(dir)) {
            try {
                for (const auto& item : fs::directory_iterator(dir, fs::directory_options::skip_permission_denied)) {
                    try {
                        SetFileAttributesW(item.path().c_str(), FILE_ATTRIBUTE_NORMAL);
                        fs::remove_all(item.path());
                    } catch (...) {}
                }
                Logger::Log(LogLevel::Success, L"Cleaned temporary folder: " + dir.wstring());
            } catch (const std::exception& e) {
                Logger::Log(LogLevel::Warning, L"Directory cleanup warning: " + ToWide(e.what()));
            }
        }
    }
}

void SystemRepair::ExecuteOfflineSFC() {
    Logger::Log(LogLevel::Info, L"Invoking System File Checker (SFC) engine...");

    std::wstring cmd = L"sfc.exe /scannow /offbootdir=" + m_env.targetSystemDrive.wstring() + 
                       L" /offwindir=" + m_env.targetWindowsDir.wstring();

    Logger::Log(LogLevel::Info, L"Executing native command: " + cmd);

    STARTUPINFOW si = { sizeof(STARTUPINFOW) };
    PROCESS_INFORMATION pi = { 0 };

    std::vector<wchar_t> cmdBuf(cmd.begin(), cmd.end());
    cmdBuf.push_back(L'\0');

    if (CreateProcessW(NULL, cmdBuf.data(), NULL, NULL, FALSE, 0, NULL, NULL, &si, &pi)) {
        WaitForSingleObject(pi.hProcess, INFINITE);
        DWORD exitCode = 0;
        GetExitCodeProcess(pi.hProcess, &exitCode);
        CloseHandle(pi.hProcess);
        CloseHandle(pi.hThread);
        Logger::Log(LogLevel::Success, L"SFC finished execution with code: " + std::to_wstring(exitCode));
    } else {
        Logger::Log(LogLevel::Error, L"Failed to spawn SFC process.");
    }
}

void SystemRepair::ResetWinsock() {
    if (m_env.isWinPE) {
        Logger::Log(LogLevel::Info, L"Skipping dynamic Winsock reset (WinPE environment active).");
        return;
    }
    Logger::Log(LogLevel::Info, L"Resetting Winsock and IP configurations...");
    system("netsh winsock reset > nul");
    system("netsh int ip reset > nul");
    Logger::Log(LogLevel::Success, L"Network stacks reset.");
}

void SystemRepair::Execute() {
    ResetHostsFile();
    ClearSuspiciousTempPaths();
    ResetWinsock();
    ExecuteOfflineSFC();
}
